func TestConstructorsReturnErrors(t *testing.T) {
	if _, err := New("", "password"); err == nil {
		t.Fatal("empty method was accepted")
	}
	if _, err := New("aes-256-cfb", ""); err == nil {
		t.Fatal("empty password was accepted")
	}
	core, err := New("aes-256-cfb", "password")
	if err != nil {
		t.Fatal(err)
	}
	if _, err := core.NewEncrypter(make([]byte, 8)); err == nil {
		t.Fatal("short IV was accepted")
	}
	if _, err := core.DecryptPacket(make([]byte, 15)); err == nil {
		t.Fatal("short packet was accepted")
	}
}
