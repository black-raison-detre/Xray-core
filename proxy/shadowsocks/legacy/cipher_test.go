func TestMethodRegistryAndRoundTrip(t *testing.T) {
	want := []struct {
		name    string
		keySize int
		ivSize  int
	}{
		{"none", 16, 0},
		{"table", 16, 0},
		{"rc4", 16, 0},
		{"rc4-md5-6", 16, 6},
		{"rc4-md5", 16, 16},
		{"aes-128-cfb", 16, 16},
		{"aes-192-cfb", 24, 16},
		{"aes-256-cfb", 32, 16},
		{"aes-128-ctr", 16, 16},
		{"aes-192-ctr", 24, 16},
		{"aes-256-ctr", 32, 16},
		{"bf-cfb", 16, 8},
		{"camellia-128-cfb", 16, 16},
		{"camellia-192-cfb", 24, 16},
		{"camellia-256-cfb", 32, 16},
		{"cast5-cfb", 16, 8},
		{"des-cfb", 8, 8},
		{"idea-cfb", 16, 8},
		{"rc2-cfb", 16, 8},
		{"seed-cfb", 16, 16},
		{"salsa20", 32, 8},
		{"chacha20", 32, 8},
		{"chacha20-ietf", 32, 12},
	}
	if got := Methods(); len(got) != len(want) {
		t.Fatalf("Methods() returned %d methods, want %d", len(got), len(want))
	}
	payload := []byte("legacy Shadowsocks chunk and UDP compatibility payload")
	for index, expected := range want {
		t.Run(expected.name, func(t *testing.T) {
			method, ok := Lookup("  " + expected.name + "  ")
			if !ok {
				t.Fatal("method not found")
			}
			if method.KeySize != expected.keySize || method.IVSize != expected.ivSize {
				t.Fatalf("metadata = key %d IV %d, want key %d IV %d", method.KeySize, method.IVSize, expected.keySize, expected.ivSize)
			}
			random := bytes.NewReader(bytes.Repeat([]byte{byte(index + 1)}, 64))
			core, err := NewWithRandom(expected.name, []byte("test-password"), random)
			if err != nil {
				t.Fatal(err)
			}
			packet, err := core.EncryptPacket(payload)
			if err != nil {
				t.Fatal(err)
			}
			if !bytes.Equal(packet[:expected.ivSize], bytes.Repeat([]byte{byte(index + 1)}, expected.ivSize)) {
				t.Fatalf("unexpected IV prefix: %x", packet[:expected.ivSize])
			}
			plain, err := core.DecryptPacket(packet)
			if err != nil {
				t.Fatal(err)
			}
			if !bytes.Equal(plain, payload) {
				t.Fatalf("round trip mismatch: %x", plain)
			}
		})
	}
}

func TestStreamChunkBoundaries(t *testing.T) {
	payload := bytes.Repeat([]byte("0123456789abcdef"), 33)
	for _, name := range Methods() {
		t.Run(name, func(t *testing.T) {
			core, err := New(name, "chunk-password")
			if err != nil {
				t.Fatal(err)
			}
			iv := bytes.Repeat([]byte{0xa5}, core.Method().IVSize)
			wholeStream, err := core.NewEncrypter(iv)
			if err != nil {
				t.Fatal(err)
			}
			whole := make([]byte, len(payload))
			wholeStream.XORKeyStream(whole, payload)

			chunkedStream, err := core.NewEncrypter(iv)
			if err != nil {
				t.Fatal(err)
			}
			chunked := make([]byte, len(payload))
			for offset, step := 0, 1; offset < len(payload); step = step%79 + 1 {
				end := min(offset+step, len(payload))
				chunkedStream.XORKeyStream(chunked[offset:end], payload[offset:end])
				offset = end
			}
			if !bytes.Equal(chunked, whole) {
				t.Fatal("ciphertext changes with write fragmentation")
			}

			decryptor, err := core.NewDecrypter(iv)
			if err != nil {
				t.Fatal(err)
			}
			plain := make([]byte, len(payload))
			for offset, step := 0, 73; offset < len(whole); step = step%31 + 1 {
				end := min(offset+step, len(whole))
				decryptor.XORKeyStream(plain[offset:end], whole[offset:end])
				offset = end
			}
			if !bytes.Equal(plain, payload) {
				t.Fatal("plaintext changes with read fragmentation")
			}
		})
	}
}

