func TestAuthSHA1v2ExtendedPaddingHeader(t *testing.T) {
	info := deterministicInfo(t, "auth_sha1_v2")
	random := make([]byte, 8+200)
	random[0] = 200
	info.Random = bytes.NewReader(random)
	p := NewProtocol("auth_sha1_v2")
	p.SetServerInfo(info)
	p.SetData(&AuthData{clientID: []byte{0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17}, connectionID: 1})
	wire, err := p.PreEncrypt([]byte{1, 127, 0, 0, 1, 0, 80})
	if err != nil {
		t.Fatal(err)
	}
	if len(wire) < 9 || wire[6] != 0xff || binary.BigEndian.Uint16(wire[7:9]) != 201 {
		t.Fatalf("extended padding header was overwritten: %x", wire[:min(len(wire), 9)])
	}
}

func TestAuthSHA1LegacyCOracleFixtures(t *testing.T) {
	// Generated by an ephemeral helper linked to shadowsocksr-libev at
	// dc8174211d9089bf3c680dd1d9e3886bc78421b9. The fixture uses
	// aes-256-cfb, password "fixture-password", IV 0x31 repeated, Unix time
	// 1700000087, client ID 1011121314151617, connection ID 0x00102030,
	// and request 017f000001005068656c6c6f. No GPL source or object is checked in.
	fixtures := map[string]string{
		"auth_sha1":    "6ed8f4f200240157f153651011121331201000017f0000010050c27e0edad61a925015d800180d00000000000000000000000068656c6c6f3a02ed08",
		"auth_sha1_v2": "15f95856002401101112131415161731201000017f0000010050d595f102f4e90a1b058000180d00000000000000000000000068656c6c6f3a02ed08",
	}
	request := []byte{1, 127, 0, 0, 1, 0, 80, 'h', 'e', 'l', 'l', 'o'}
	for _, name := range []string{"auth_sha1", "auth_sha1_v2"} {
		t.Run(name, func(t *testing.T) {
			info := deterministicInfo(t, name)
			info.Now = func() time.Time { return time.Unix(1700000087, 0) }
			// RandomInt consumes eight bytes for each frame. The C xorshift
			// results are 0 and 12; the following twelve bytes are padding.
			random := make([]byte, 28)
			random[8] = 12
			info.Random = bytes.NewReader(random)
			p := NewProtocol(name)
			p.SetServerInfo(info)
			p.SetData(&AuthData{clientID: []byte{0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17}, connectionID: 0x00102030})
			got, err := p.PreEncrypt(request)
			if err != nil {
				t.Fatal(err)
			}
			want, err := hex.DecodeString(fixtures[name])
			if err != nil {
				t.Fatal(err)
			}
			if !bytes.Equal(got, want) {
				t.Fatalf("fixture mismatch\n got %x\nwant %x", got, want)
			}
		})
	}
}

func deterministicInfo(t *testing.T, name string) *ssr.ServerInfo {
	t.Helper()
	c, err := legacy.New("aes-256-cfb", "fixture-password")
	if err != nil {
		t.Fatal(err)
	}
	key := c.Key()
	return &ssr.ServerInfo{
		Host: "example.com", Port: 443, Param: "1001:user:key#3600", IV: bytes.Repeat([]byte{0x31}, 16), IVLen: 16,
		Key: key, KeyLen: len(key), HeadLen: 7, TcpMss: 1460, Overhead: 13,
		Random: bytes.NewReader(bytes.Repeat([]byte{0x5a}, 1<<20)), Now: func() time.Time { return time.Unix(1700000000, 0) },
	}
}

func TestActiveProtocolRegistryAndUplinkFraming(t *testing.T) {
	request := []byte{1, 127, 0, 0, 1, 0, 80, 'h', 'e', 'l', 'l', 'o'}
	for _, name := range activeProtocols {
		t.Run(name, func(t *testing.T) {
			p := NewProtocol(name)
			if p == nil {
				t.Fatalf("protocol %q is not registered", name)
			}
			p.SetServerInfo(deterministicInfo(t, name))
			p.SetData(p.GetData())
			wire, err := p.PreEncrypt(request)
			if err != nil {
				t.Fatal(err)
			}
			if len(wire) == 0 {
				t.Fatal("first payload produced no wire data")
			}
		})
	}
}

func FuzzProtocolDecoders(f *testing.F) {
	f.Add([]byte{})
	f.Add([]byte{0, 8, 0, 0, 0, 0, 0, 0})
	f.Add(bytes.Repeat([]byte{0xff}, 64))
	f.Fuzz(func(t *testing.T, data []byte) {
		if len(data) > 64*1024 {
			t.Skip()
		}
		for _, name := range activeProtocols {
			p := NewProtocol(name)
			p.SetServerInfo(deterministicInfo(t, name))
			p.SetData(p.GetData())
			_, _ = p.PreEncrypt([]byte{1, 127, 0, 0, 1, 0, 80, 'x'})
			_, _, _ = p.PostDecrypt(data)
		}
	})
}
